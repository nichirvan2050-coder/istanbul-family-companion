export function localizeTransportMode(mode: TransportMode, locale: Locale): TransportMode {
  if (locale === "en") return mode;
  const tr = transportModeTranslations[mode.id]?.[locale];
  if (!tr) return mode;
  return {
    ...mode,
    title: tr.title,
    summary: tr.summary,
    notes: tr.notes,
    lines: mode.lines?.map((line, i) => ({ ...line, usefulFor: tr.usefulFor?.[i] ?? line.usefulFor })),
  };
}

export function localizeIstanbulkart(locale: Locale): typeof istanbulkartEn {
  if (locale === "en") return istanbulkartEn;
  const tr = istanbulkartTranslations[locale];
  return { ...istanbulkartEn, ...tr };
}

export function localizeFareTable(fareTable: FareRow[], locale: Locale): FareRow[] {
  if (locale === "en") return fareTable;
  const tr = fareTableTranslations[locale];
  return fareTable.map((row, i) => (tr[i] ? { ...row, transport: tr[i].transport, fareType: tr[i].fareType, notes: tr[i].notes || row.notes } : row));
}
