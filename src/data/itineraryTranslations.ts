export function localizeItineraryDay(day: ItineraryDay, locale: Locale): ItineraryDay {
  if (locale === "en") return day;
  const tr = itineraryTranslations[day.day]?.[locale];
  if (!tr) return day;
  return {
    ...day,
    title: tr.title,
    subtitle: tr.subtitle,
    transport: tr.transport,
    timeline: day.timeline.map((stop: DayStop, i: number): DayStop => {
      const st = tr.timeline[i];
      if (!st) return stop;
      return { ...stop, label: st.label ?? stop.label, detail: st.detail ?? stop.detail };
    }),
  };
}
