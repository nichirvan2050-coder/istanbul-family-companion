export function localizeArea(area: Area, locale: Locale): Area {
  if (locale === "en") return area;
  const tr = areaTranslations[area.id]?.[locale];
  if (!tr) return area;
  return {
    ...area,
    whyFamilies: tr.whyFamilies,
    transport: tr.transport,
    parksWaterfront: tr.parksWaterfront ?? area.parksWaterfront,
    food: tr.food ?? area.food,
    shopping: tr.shopping ?? area.shopping,
    evening: tr.evening ?? area.evening,
    considerations: tr.considerations ?? area.considerations,
  };
}
